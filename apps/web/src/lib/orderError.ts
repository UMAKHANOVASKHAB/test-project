import { ApiError } from './apiError'

/** Что сказать гостю, если заказ не принят. Раньше на всё было «проверьте интернет», даже когда связь ни при чём */
export function orderErrorText(e: unknown): string {
  if (e instanceof ApiError) {
    if (e.code === 'open in telegram') return 'Заказ можно отправить только из Telegram: откройте меню через бота @ninebar_coffee_05bot.'
    if (e.code === 'bad init data') return 'Сессия устарела. Закройте мини-апп и откройте заново из бота, корзину придётся собрать ещё раз.'
    if (e.code === 'pickup time passed') return 'Выбранное время уже прошло. Выберите другое и нажмите «Заказать».'
    if (e.code === 'pickup time closed') return 'На это время кофейня не работает. Выберите другое время.'
    if (e.code === 'free coffee not available') return 'Бесплатный кофе уже использован в другом заказе. Снимите галочку и закажите снова.'
    if (e.status >= 500) return 'У нас временная ошибка. Подождите минуту и нажмите «Заказать» ещё раз: второй заказ не появится.'
  }
  return 'Заказ не отправился. Проверьте интернет и нажмите «Заказать» ещё раз: второй заказ не появится.'
}
